#!/usr/bin/env node
// Regenerates plugin/palettes.lua from the upstream evergarden palettes.
//
// Source of truth: the evergarden nvim port, which is the most complete
// reference implementation. Its `winter`, `fall`, `spring` and `summer`
// palettes are byte-for-byte identical to the `evergarden` Rust crate
// (v0.1.0) that Whiskers generates the other ports from. The crate does not
// (yet) ship `lunar`, so nvim is used as the source for all five flavors.
//
// Usage: node scripts/build-palettes.mjs [--check]
//
//   --check  exit non-zero if plugin/palettes.lua is out of date instead of
//            rewriting it.

import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const OUTPUT = join(ROOT, 'plugin', 'palettes.lua')

const UPSTREAM =
  'https://codeberg.org/evergarden/nvim/raw/branch/main/lua/evergarden/palettes'

// Canonical order, used for cycling. Flavors are ordered from darkest to
// lightest, with the light flavor last and `lunar` (night) appended.
const FLAVORS = ['winter', 'fall', 'spring', 'summer', 'lunar']

const ACCENTS = [
  'red',
  'orange',
  'yellow',
  'lime',
  'green',
  'aqua',
  'skye',
  'snow',
  'blue',
  'purple',
  'pink',
  'cherry',
]

const NEUTRALS = [
  'text',
  'subtext1',
  'subtext0',
  'overlay2',
  'overlay1',
  'overlay0',
  'surface2',
  'surface1',
  'surface0',
  'base',
  'mantle',
  'crust',
]

const COLOR_ORDER = [...ACCENTS, ...NEUTRALS]

function titleCase(s) {
  return s.charAt(0).toUpperCase() + s.slice(1)
}

async function fetchPalette(flavor) {
  const url = `${UPSTREAM}/${flavor}.lua`
  const res = await fetch(url)
  if (!res.ok) {
    throw new Error(`failed to fetch ${url}: ${res.status} ${res.statusText}`)
  }
  const source = await res.text()

  const colors = {}
  for (const [, key, hex] of source.matchAll(
    /^\s*([A-Za-z][A-Za-z0-9_]*)\s*=\s*['"](#[0-9a-fA-F]{6})['"]/gm,
  )) {
    colors[key] = hex.toLowerCase()
  }

  const missing = COLOR_ORDER.filter((k) => !(k in colors))
  if (missing.length > 0) {
    throw new Error(`${flavor}: palette is missing ${missing.join(', ')}`)
  }
  return colors
}

// Perceived luminance of `base`, used to flag light flavors so consumers can
// pick a sensible default without hardcoding the flavor list.
function isDark(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)
  const luminance = 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)
  return luminance < 0.5
}

function render(palettes) {
  const lines = [
    '-- This file is generated by scripts/build-palettes.mjs. Do not edit by hand.',
    '-- Source: https://codeberg.org/evergarden/nvim (lua/evergarden/palettes/*.lua)',
    '',
    'return {',
    '  -- Flavors in cycle order.',
    `  order = { ${FLAVORS.map((f) => `'${f}'`).join(', ')} },`,
    '',
    '  -- Accent colors in cycle order. Every flavor defines all of these.',
    `  accents = { ${ACCENTS.map((a) => `'${a}'`).join(', ')} },`,
    '',
    '  flavors = {',
  ]

  for (const flavor of FLAVORS) {
    const colors = palettes[flavor]
    lines.push(`    ${flavor} = {`)
    lines.push(`      name = '${titleCase(flavor)}',`)
    lines.push(`      dark = ${isDark(colors.base)},`)
    lines.push('      colors = {')
    for (const key of COLOR_ORDER) {
      lines.push(`        ${key} = '${colors[key]}',`)
    }
    lines.push('      },')
    lines.push('    },')
  }

  lines.push('  },', '}', '')
  return lines.join('\n')
}

const check = process.argv.includes('--check')

const entries = await Promise.all(
  FLAVORS.map(async (flavor) => [flavor, await fetchPalette(flavor)]),
)
const rendered = render(Object.fromEntries(entries))

if (check) {
  let current = ''
  try {
    current = await readFile(OUTPUT, 'utf8')
  } catch {
    // fall through to the "out of date" error below
  }
  if (current !== rendered) {
    console.error('plugin/palettes.lua is out of date; run `just build`')
    process.exit(1)
  }
  console.log('plugin/palettes.lua is up to date')
} else {
  await writeFile(OUTPUT, rendered)
  console.log(`wrote ${OUTPUT} (${FLAVORS.length} flavors)`)
}
